//! Content area (CMS.6, decision 0049): the Space pages for the content that moves into Space: per-scope wiki, docs and blog
//! trees (the scope home), the page with the shared block editor, collections admin, the media library and reviews.
//!
//! Each page's plain logic is a module here (state, requests, the rows as plain values). The window side is a trait per page,
//! and [`wire_content!`] implements all of them for the generated window. The app expands the macro in its own crate, where
//! the Slint types are in scope (the company and projects pattern).
//!
//! Modules: `routes` (paths), `scope` (scopes, access, the move rules), `view` (rows, labels, slugs), `home` (scope home),
//! `page` (one page and edit mode), `review` (drafts and reviews), `collections` (admin), `media` (library and picker).
//!
//! The markup is in [`UI_DIR`]; the app compiles it through the `@space_area_content` library path. The app's `build.rs` also
//! registers `rimelight_editor`'s markup (the page's editor is `rimelight_editor::wire_block_editor!` in the app crate).
//!
//! Every user-visible string is an English literal for now. The area has no `space_i18n` calls yet, the same as the company
//! area; `space_i18n` is still a placeholder (UNSURE, see WIRING.md).

pub use rimelight_editor;
