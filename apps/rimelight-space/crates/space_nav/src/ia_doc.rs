//! Renders the manifest as Markdown for `PROJECT.md section 6.5` (`cargo xtask docs ia`). Deterministic: areas in rail order,
//! sections in manifest order, pages in manifest order. Pure data, no file access (the xtask writes the file).

use std::fmt::Write;

use crate::{Area, pages, sections_in};

/// The whole `PROJECT.md section 6.5` file as one string.
pub fn render() -> String {
    let all = pages();
    let records = all.iter().filter(|p| p.has_params()).count();
    let mut out = String::new();
    out.push_str("# Information architecture\n\n");
    out.push_str(
        "Generated by `cargo xtask docs ia` from the navigation manifest in `crates/space_nav`. Do not edit by hand.\n\n",
    );
    let _ = writeln!(
        out,
        "{} routes: {} sidebar rows and {} record routes (with a `:name` parameter).\n",
        all.len(),
        all.len() - records,
        records
    );
    for area in Area::ALL {
        let _ = writeln!(out, "## {}\n", area.title());
        for section in sections_in(area) {
            let _ = writeln!(out, "### {}\n", section.title);
            out.push_str("| Kind | Route | Title | Icon | Primary action |\n");
            out.push_str("|---|---|---|---|---|\n");
            for page in all.iter().filter(|p| p.section == section.id) {
                let kind = if page.has_params() { "record" } else { "row" };
                let action = page.primary_action.unwrap_or("-");
                let _ = writeln!(
                    out,
                    "| {kind} | `{}` | {} | {} | {action} |",
                    page.route,
                    page.title,
                    page.icon()
                );
            }
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn renders_every_route_once_and_is_deterministic() {
        let doc = render();
        assert_eq!(doc, render(), "same input, same output");
        for page in crate::pages() {
            let cell = format!("| `{}` |", page.route);
            assert_eq!(doc.matches(&cell).count(), 1, "{} once", page.route);
        }
        assert!(doc.contains("## People"));
        assert!(doc.contains("### HR records"));
    }
}
